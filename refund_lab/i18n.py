def translate(text: str, language: str = "en") -> str:
    return EN.get(text, text) if language == "en" else text


def translate_tree(value, language: str = "en"):
    """Translate known display messages without changing stored business records."""
    if isinstance(value, str):
        return translate(value, language)
    if isinstance(value, list):
        return [translate_tree(item, language) for item in value]
    if isinstance(value, dict):
        return {key: translate_tree(item, language) for key, item in value.items()}
    return value
